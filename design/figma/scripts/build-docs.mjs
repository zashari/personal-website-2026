#!/usr/bin/env node
// Turns the extracted JSON specs into readable per-sheet reference pages under design/figma/docs/sheets.
// usage: node design/figma/scripts/build-docs.mjs   (run extract.mjs first)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const DATA = path.join(ROOT, 'data');
const OUT = path.join(ROOT, 'docs', 'sheets');
const meta = JSON.parse(fs.readFileSync(path.join(DATA, 'meta.json'), 'utf8'));

const cell = (v) => String(v ?? '').replace(/\|/g, '\\|').replace(/\n/g, '<br>');
const box = (b) => (b ? `${b.x}, ${b.y}` : '');
const size = (b) => (b ? `${b.w} × ${b.h}` : '');
const fill = (n) => (n.fills || []).map((p) => (p.type === 'SOLID' ? `${p.color}${p.opacity ? ` @${p.opacity}` : ''}` : p.type.toLowerCase())).join(', ');
const fx = (n) => (n.effects || []).map((e) => {
  if (e.type === 'TEXTURE') return `texture r${e.radius} n${Math.round(e.noiseSize * 100) / 100}`;
  if (e.type === 'DROP_SHADOW') return `shadow ${e.offset.x},${e.offset.y} b${e.radius} ${e.color}@${e.alpha}`;
  if (e.type === 'NOISE') return `noise ${Math.round(e.noiseSize * 100) / 100} ${e.color}@${e.alpha}`;
  if (e.type === 'LAYER_BLUR') return `blur ${e.radius}`;
  return e.type.toLowerCase();
}).join('; ');
const group = (n) => n.path.split(' / ').slice(1).filter((p) => !/^Group \d+$/.test(p)).join(' › ');
const table = (head, rows) => (rows.length ? [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n') : '_None._');

function textRows(nodes) {
  return nodes.filter((n) => n.type === 'TEXT').map((n) => {
    const s = n.style;
    const runs = (n.runs || []).filter((r) => r.style).map((r) => `"${r.text.trim()}": ${[r.style.fontStyle, r.style.fills?.[0]?.color, r.style.textDecoration].filter(Boolean).join(' ')}`).join('; ');
    return [
      group(n),
      n.text + (n.redactedBy ? ' *(masked)*' : ''),
      `${s.family} ${s.style}`,
      s.size,
      s.lineHeight === 'auto' ? `auto (${s.lineHeightPx})` : s.lineHeight,
      s.letterSpacing || 0,
      s.align.toLowerCase(),
      fill(n) + (runs ? `; runs: ${runs}` : ''),
      box(n.box),
      size(n.box),
      [n.rotationDeg && `rot ${n.rotationDeg}°`, fx(n), n.style.textDecoration?.toLowerCase(), n.autoResize === 'NONE' ? 'fixed box' : n.autoResize === 'HEIGHT' ? 'fixed width' : ''].filter(Boolean).join('; '),
    ];
  });
}

function shapeRows(nodes) {
  return nodes.filter((n) => ['RECTANGLE', 'VECTOR', 'LINE', 'ELLIPSE'].includes(n.type) && !n.fills?.some((p) => p.type === 'IMAGE')).map((n) => [
    group(n) + (group(n) ? ' › ' : '') + n.name,
    n.role ?? (n.box.h === 0 || n.box.w === 0 ? 'line' : n.type.toLowerCase()),
    fill(n),
    n.stroke ? `${n.stroke.paints.map((p) => p.color).join()} ${n.stroke.weight}px ${n.stroke.align.toLowerCase()}${n.stroke.dashes ? ` dash ${n.stroke.dashes.join(' ')}` : ''}${n.stroke.cap ? ` cap ${n.stroke.cap.toLowerCase()}` : ''}` : '',
    box(n.box),
    size(n.box),
    [n.rotationDeg && `rot ${n.rotationDeg}°`, n.blendMode?.toLowerCase(), fx(n), n.cornerRadius && `radius ${n.cornerRadius}`].filter(Boolean).join('; '),
  ]);
}

function imageRows(nodes) {
  return nodes.filter((n) => n.fills?.some((p) => p.type === 'IMAGE')).map((n) => {
    const p = n.fills.find((f) => f.type === 'IMAGE');
    return [
      group(n) + (group(n) ? ' › ' : '') + n.name,
      p.imageRef.slice(0, 8),
      p.scaleMode.toLowerCase() + (p.filters ? ` filters ${JSON.stringify(p.filters)}` : ''),
      box(n.box),
      size(n.box),
      [n.rotationDeg && `rot ${n.rotationDeg}°`, n.blendMode?.toLowerCase(), n.stroke && `frame ${n.stroke.paints[0].color} ${n.stroke.weight}px`, fx(n), n.holes && `${n.holes.count} punched holes ⌀${n.holes.diameter} at x ${n.holes.x}`].filter(Boolean).join('; '),
    ];
  });
}

function groupRows(nodes) {
  return nodes.filter((n) => n.type === 'GROUP' && (n.effects || n.opacity)).map((n) => [group(n) + (group(n) ? ' › ' : '') + n.name, box(n.box), size(n.box), [n.opacity && `opacity ${n.opacity}`, fx(n)].filter(Boolean).join('; ')]);
}

function page(title, file, intro, spec) {
  const nodes = spec.nodes;
  const masked = nodes.filter((n) => n.redactedBy);
  const md = `# ${title}

${intro}

- Figma node: \`${spec.id}\` (${spec.name}), ${spec.size.w} × ${spec.size.h} Figma px. The site's PNG masters are 4× this.
- Coordinates are Figma px from the top-left of this node's bounding box. Sizes are width × height. Positions are of the axis-aligned bounding box, so rotated layers report their rotated extent. Rotation is clockwise-positive, as in CSS rotate().
- Source data: \`data/${file}\`. Generated by \`scripts/build-docs.mjs\` from file version ${meta.version} (${meta.lastModified}).
${masked.length ? `- ${masked.length} text layer(s) sit under redaction bars. Their real words are masked (█); see \`docs/09-redactions-and-privacy.md\`.` : ''}

## Text (${nodes.filter((n) => n.type === 'TEXT').length} layers)

${table(['Group', 'Text', 'Font', 'Size', 'Line height', 'Tracking', 'Align', 'Colour', 'x, y', 'w × h', 'Notes'], textRows(nodes))}

## Lines, boxes and marks

${table(['Layer', 'Role', 'Fill', 'Stroke', 'x, y', 'w × h', 'Notes'], shapeRows(nodes))}

## Images

${table(['Layer', 'Image ref', 'Scale', 'x, y', 'w × h', 'Notes'], imageRows(nodes))}

## Group effects

${table(['Group', 'x, y', 'w × h', 'Effects'], groupRows(nodes))}
`;
  return md;
}

const SHEETS = [
  ['personal-info', 'Personal info', 'Folder 001. Subject info, education, subject summary table, status footer, two clipped polaroids.'],
  ['professional-info', 'Professional info', 'Folder 002. Operations log: intro paragraph with photo and red arrow, mission timeline, technical loadout, protocol and velocity panels.'],
  ['projects-page-1', 'Projects, page 1 (HP/3-A)', 'Folder 003, first page. Three stapled project cards with QR codes.'],
  ['projects-page-2', 'Projects, page 2 (HP/3-B)', 'Folder 003, second page. Two project cards and the empty "[submit project here]" slot.'],
];

fs.mkdirSync(OUT, { recursive: true });
for (const [name, title, intro] of SHEETS) {
  for (const side of ['front', 'back']) {
    const file = `sheets/${name}.${side}.json`;
    const spec = JSON.parse(fs.readFileSync(path.join(DATA, file), 'utf8'));
    const t = `${title}: ${side}`;
    const i = side === 'front' ? intro : `Back of the ${title.toLowerCase()} sheet: blank paper, mirrored, plus whatever shows through from the front (photo backs, paperclips, card edges).`;
    fs.writeFileSync(path.join(OUT, `${name}.${side}.md`), page(t, file, i, spec));
  }
}
const home = JSON.parse(fs.readFileSync(path.join(DATA, 'home.json'), 'utf8'));
fs.writeFileSync(path.join(OUT, 'home.md'), page('Home: folder stack', 'home.json', 'The 1728 × 1117 desktop home frame: four folders stacked bottom-up (001 at the front). Folder 004 is in Figma but not on the live site.', home));
const assets = JSON.parse(fs.readFileSync(path.join(DATA, 'assets.json'), 'utf8'));
fs.writeFileSync(path.join(OUT, 'assets-board.md'), page('Assets board', 'assets.json', 'The ASSETS group: polaroid fronts and handwritten backs, the paper texture, the blank paper, the stapler and the logo.', assets));
console.log(`Wrote ${SHEETS.length * 2 + 2} pages to ${path.relative(process.cwd(), OUT)}`);
