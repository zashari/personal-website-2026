#!/usr/bin/env node
// Builds the hand-drawn lines of the contact section (/contact, and the bottom of /home) from the Figma frame
// "cta-desktop", exported as SVG with text kept as text (design/figma/data/cta-desktop-light.svg; dark differs only in
// colour, which the page sets).
// - src/contact/lines.js: the path data of the circle round the horse, the horizontal line through it and the brush
//   stroke before the changing word, in the frame's px
// usage: node scripts/build-contact-assets.mjs
import fs from 'node:fs';

const SVG = 'design/figma/data/cta-desktop-light.svg';
const OUT = 'src/contact/lines.js';
// Figma layer name -> export name.
const LINES = { 'Ellipse 4': 'circle', 'Line 31': 'rule', 'Line 32': 'brush' };

const svg = fs.readFileSync(SVG, 'utf8');
const paths = Object.entries(LINES).map(([layer, name]) => {
  const d = svg.match(new RegExp(`<path id="${layer}" d="([^"]+)"`))?.[1];
  if (!d) throw new Error(`no path "${layer}" in ${SVG}`);
  // A hundredth of a frame px is finer than any screen shows it.
  return [name, d.replace(/-?\d*\.\d+/g, (v) => String(+(+v).toFixed(2)))];
});

const lines = [
  `// Generated by scripts/build-contact-assets.mjs from ${SVG}; do not edit.`,
  "// The contact section's hand-drawn lines, as path data in the 1920 x 1080 frame's px.",
  ...paths.map(([name, d]) => `export const ${name.toUpperCase()} = '${d}';`),
  '',
];
fs.mkdirSync('src/contact', { recursive: true });
fs.writeFileSync(OUT, lines.join('\n'));
console.log(`${OUT} ${(fs.statSync(OUT).size / 1024).toFixed(1)} kB`);
