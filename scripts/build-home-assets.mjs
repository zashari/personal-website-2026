#!/usr/bin/env node
// Builds the /home assets from the Figma frame "home" (page version-2, node 2016:10).
// - src/home/assets/golden-spiral.svg: the golden-ratio lines, traced from Figma's own outlined geometry, with a bleed
// - src/home/assets/images/photo.{avif,webp}: the centre photo, from the original image fill in design/source/home
// - src/home/assets/images/reel/NN.{avif,webp}: the photos shown in turn while the centre photo is hovered
// usage: node scripts/build-home-assets.mjs   (data: design/figma/data/home-v2.json, the /v1/files/:key/nodes?ids=2016:2&geometry=paths response)
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const DATA = 'design/figma/data/home-v2.json';
const OUT = 'src/home/assets';
const FRAME_ID = '2016:10';
const SPIRAL_ID = '2020:78';
// Lines that end on the frame's edge in Figma run on past it, so a viewport wider or taller than 16:9 keeps them unbroken.
const BLEED = 2000;

const page = Object.values(JSON.parse(fs.readFileSync(DATA, 'utf8')).nodes)[0].document;

function find(node, id) {
  if (node.id === id) return node;
  for (const child of node.children ?? []) {
    const hit = find(child, id);
    if (hit) return hit;
  }
  return null;
}

// Figma's relativeTransform is [[a, c, e], [b, d, f]], relative to the parent node (groups included).
const multiply = ([[a1, c1, e1], [b1, d1, f1]], [[a2, c2, e2], [b2, d2, f2]]) => [
  [a1 * a2 + c1 * b2, a1 * c2 + c1 * d2, a1 * e2 + c1 * f2 + e1],
  [b1 * a2 + d1 * b2, b1 * c2 + d1 * d2, b1 * e2 + d1 * f2 + f1],
];
const round = (n) => +n.toFixed(4);
const toMatrix = ([[a, c, e], [b, d, f]]) => [a, b, c, d, e, f].map(round).join(' ');
const hex = ({ r, g, b }) => '#' + [r, g, b].map((v) => Math.round(v * 255).toString(16).padStart(2, '0')).join('');

const apply = ([[a, c, e], [b, d, f]], [x, y]) => [a * x + c * y + e, b * x + d * y + f];

function extendToBleed([x, y], W, H) {
  const out = (v, max) => (v <= 0.5 ? v - BLEED : v >= max - 0.5 ? v + BLEED : v);
  return [out(x, W), out(y, H)];
}

function paths(node, transform, out, W, H) {
  if (node.visible === false) return;
  const own = multiply(transform, node.relativeTransform);
  if (node.type === 'LINE') {
    // Figma's outlined line is the band y = -strokeWeight..0 in the line's own space; draw its centre line instead.
    const colour = node.strokes.find((p) => p.visible !== false && p.type === 'SOLID');
    const half = -node.strokeWeight / 2;
    const [x1, y1] = extendToBleed(apply(own, [0, half]), W, H);
    const [x2, y2] = extendToBleed(apply(own, [node.size.x, half]), W, H);
    out.push(`  <line x1="${round(x1)}" y1="${round(y1)}" x2="${round(x2)}" y2="${round(y2)}" stroke="${hex(colour.color)}" stroke-width="${node.strokeWeight}"/>`);
    return;
  }
  const paint = (geometry, paints) => {
    const colour = paints?.find((p) => p.visible !== false && p.type === 'SOLID');
    if (!colour || !geometry?.length) return;
    for (const g of geometry) {
      const rule = g.windingRule === 'EVENODD' ? ' fill-rule="evenodd"' : '';
      out.push(`  <path transform="matrix(${toMatrix(own)})" fill="${hex(colour.color)}"${rule} d="${g.path}"/>`);
    }
  };
  paint(node.fillGeometry, node.fills);
  paint(node.strokeGeometry, node.strokes);
  // A boolean operation's fillGeometry already is the combined outline; its children are only operands.
  if (node.type === 'BOOLEAN_OPERATION') return;
  for (const child of node.children ?? []) paths(child, own, out, W, H);
}

const frame = find(page, FRAME_ID);
const spiral = find(frame, SPIRAL_ID);
const { x: W, y: H } = frame.size;
const body = [];
paths(spiral, [[1, 0, 0], [0, 1, 0]], body, W, H);
// The canvas reaches BLEED px past the frame on every side; the page places it at (-BLEED, -BLEED).
const svg = [
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${-BLEED} ${-BLEED} ${W + 2 * BLEED} ${H + 2 * BLEED}" width="${W + 2 * BLEED}" height="${H + 2 * BLEED}">`,
  `  <!-- Generated by scripts/build-home-assets.mjs from Figma node ${SPIRAL_ID}; do not edit by hand. -->`,
  ...body,
  '</svg>',
  '',
].join('\n');
fs.writeFileSync(path.join(OUT, 'golden-spiral.svg'), svg);
console.log(`golden-spiral.svg: ${body.length} paths`);

// The photo box is 486 x 607 and Figma fills it (cover); the original is narrower than the box's aspect, so its width
// sets the scale. 972 px covers the box on 2x screens; the browser crops the rest with object-fit: cover.
const photo = 'design/source/home/photo.jpg';
fs.mkdirSync(path.join(OUT, 'images'), { recursive: true });
await sharp(photo).rotate().resize({ width: 972 }).avif({ quality: 70, effort: 6 }).toFile(path.join(OUT, 'images', 'photo.avif'));
await sharp(photo).rotate().resize({ width: 972 }).webp({ quality: 85, effort: 5 }).toFile(path.join(OUT, 'images', 'photo.webp'));
console.log('photo.avif, photo.webp');

// Hover reel: the photos the centre image flips through while hovered. The originals are large camera JPEGs kept out
// of git (.tmp/images/home-material); only the encodes are committed. Each keeps its own aspect ratio and is scaled to
// 2x the photo box's 607 px height, with all metadata (including GPS) dropped.
const REEL_SRC = '.tmp/images/home-material';
const REEL_OUT = path.join(OUT, 'images', 'reel');
if (fs.existsSync(REEL_SRC)) {
  fs.rmSync(REEL_OUT, { recursive: true, force: true });
  fs.mkdirSync(REEL_OUT, { recursive: true });
  const files = fs.readdirSync(REEL_SRC).filter((f) => /.(jpe?g|png)$/i.test(f)).sort();
  for (const [i, file] of files.entries()) {
    const name = String(i + 1).padStart(2, '0');
    const frame = () => sharp(path.join(REEL_SRC, file)).rotate().resize({ height: 1214 });
    await frame().avif({ quality: 55, effort: 6 }).toFile(path.join(REEL_OUT, `${name}.avif`));
    await frame().webp({ quality: 78, effort: 5 }).toFile(path.join(REEL_OUT, `${name}.webp`));
  }
  console.log(`reel: ${files.length} frames`);
} else {
  console.log(`reel: skipped, ${REEL_SRC} not found`);
}
